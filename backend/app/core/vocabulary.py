# "flat191" / "кв15" / "эт3" — буквенное ключевое слово вплотную к цифре.
# Отдельный список: в APARTMENT_KEYWORDS/... стоят lookahead-запреты на цифру,
# которые несовместимы с поиском слитного написания.
GLUED_PREFIX_KEYWORDS = "|".join(
    re.escape(word)
    for word in sorted(
        {
            "квартира", "квартиру", "квартал", "микрорайон", "подъезд", "подьезд",
            "этаж", "кв", "flat", "kv", "эт", "дом", "д", "мкр", "под", "үй",
            "пәтер", "қабат", "floor", "корпус", "литер", "офис",
        },
        key=len,
        reverse=True,
    )
)
GLUED_KEYWORD_DIGIT_RE = re.compile(
    rf"(?<![0-9a-zа-яё])(?P<kw>{GLUED_PREFIX_KEYWORDS})(?P<num>\d{{1,4}})",
    re.IGNORECASE,
)
# "г.Алматы", "ул.Абая" — точка без пробела перед словом
GLUED_DOT_WORD_RE = re.compile(r"(?<=\.)(?=[0-9a-zа-яё])", re.IGNORECASE)
# "Актобе/Ақтөбе" — двуязычная склейка: части разделяем, чтобы в поиск по БД
# шла только русская половина (`raw_address` не меняется).
GLUED_SLASH_WORD_RE = re.compile(r"(?<=[а-яёa-z])(?=/)|(?<=/)(?=[а-яёa-z])", re.IGNORECASE)


# --------------------------------------------------------------------------- #
# Слитные написания -> смысловые подсказки
# --------------------------------------------------------------------------- #

# Ключевое слово -> поле результата (для разлепленных написаний, где число
# однозначно принадлежит ключевому слову: "12дом", "flat191", "4подьезд").
_KEYWORD_FIELD: dict[str, str] = {
    "дом": "house", "үй": "house", "house": "house", "литер": "house",
    "строение": "house", "корпус": "house",
    "квартира": "apartment", "квартиру": "apartment", "кв": "apartment",
    "flat": "apartment", "kv": "apartment", "пәтер": "apartment",
    "подъезд": "entrance", "подьезд": "entrance", "под": "entrance",
    "entrance": "entrance", "п-д": "entrance",
    "этаж": "floor", "эт": "floor", "floor": "floor", "қабат": "floor",
    "микрорайон": "living_area", "мкр": "living_area", "квартал": "living_area",
}


def field_for_keyword(keyword: str) -> str | None:
    """Поле, к которому относится ключевое слово слитного написания."""
    key = keyword.strip().lower().replace(".", "")
    if key in _KEYWORD_FIELD:
        return _KEYWORD_FIELD[key]
    for suffix in ("а", "у", "ы", "и", "е", "ой", "сі", "сы", "і"):
        if key.endswith(suffix) and key[: -len(suffix)] in _KEYWORD_FIELD:
            return _KEYWORD_FIELD[key[: -len(suffix)]]
    return None


def canonical_street_type(raw: str | None) -> str | None:
    """Приведение типа улицы к базовому слову ("ул." -> "улица")."""
    if not raw:
        return None
    key = raw.strip().lower().replace(".", "")
    if key in STREET_TYPE_CANONICAL:
        return STREET_TYPE_CANONICAL[key]
    # Отбрасываем казахские посессивные окончания: "көшесі" -> "көше"
    for suffix in ("сі", "сы", "і", "ы"):
        if key.endswith(suffix) and key[: -len(suffix)] in STREET_TYPE_CANONICAL:
            return STREET_TYPE_CANONICAL[key[: -len(suffix)]]
    return None
